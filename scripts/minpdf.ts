/**
 * Minimal single-page PDF writer — no dependencies.
 * Produces a valid PDF 1.4 document with Helvetica text lines.
 * Used to generate realistic demo documents for seeded data.
 */
export function makePdf(title: string, lines: string[]): Buffer {
  const esc = (s: string) =>
    s.replace(/[^\x20-\x7E]/g, "?").replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");

  const contentParts: string[] = [
    "BT /F2 16 Tf 56 770 Td",
    `(${esc(title)}) Tj`,
    "ET",
    `BT /F1 10 Tf 56 744 Td 16 TL`,
    ...lines.map((l) => `(${esc(l)}) Tj T*`),
    "ET",
    // footer
    `BT /F1 8 Tf 56 40 Td (${esc("Demo document generated by Seva Flow Karnataka - fictional data")}) Tj ET`,
  ];
  const stream = contentParts.join("\n");

  const objects: string[] = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, i) => {
    offsets.push(Buffer.byteLength(pdf));
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefPos = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const off of offsets) {
    pdf += `${String(off).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;
  return Buffer.from(pdf, "binary");
}

/** Simple SVG placeholder for field-visit photographs. */
